-- 2. DYNAMIC DATA MASKING POLICY
-- Sensitive procurement pricing & freight expenses masked for non-authorized personas
CREATE OR REPLACE MASKING POLICY GOV.MASK_COST_DATA AS (val FLOAT) RETURNS FLOAT ->
    CASE 
        WHEN CURRENT_ROLE() IN ('ONTO_PROCUREMENT', 'ONTO_JUDGE', 'ACCOUNTADMIN') THEN val
        ELSE NULL -- Masked out for Logistics & Planner
    END;

-- Apply Masking Policy to Base Tables
ALTER TABLE ONTO_HACKATHON.CORE.CORE_PART MODIFY COLUMN unit_cost SET MASKING POLICY GOV.MASK_COST_DATA;
ALTER TABLE ONTO_HACKATHON.CORE.CORE_SHIPMENT MODIFY COLUMN freight_cost SET MASKING POLICY GOV.MASK_COST_DATA;

-- 3. ROW ACCESS POLICIES (RAP)
-- Base tables are entitled; MART_OTD_AGGREGATE is RAP-unrestricted!
CREATE OR REPLACE ROW ACCESS POLICY GOV.RAP_ORDER_LINE AS (plant_id VARCHAR) RETURNS BOOLEAN ->
    CASE
        WHEN CURRENT_ROLE() IN ('ONTO_PLANNER', 'ONTO_JUDGE', 'ACCOUNTADMIN') THEN TRUE
        WHEN CURRENT_ROLE() = 'ONTO_PROCUREMENT' THEN TRUE
        WHEN CURRENT_ROLE() = 'ONTO_LOGISTICS' AND plant_id IN ('P01', 'P03', 'P07', 'P09') THEN TRUE
        ELSE FALSE
    END;

ALTER TABLE ONTO_HACKATHON.CORE.CORE_ORDER_LINE ADD ROW ACCESS POLICY GOV.RAP_ORDER_LINE ON (plant_id);

