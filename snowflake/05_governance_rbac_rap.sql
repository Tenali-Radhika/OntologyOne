    log_id                          VARCHAR(64) DEFAULT UUID_STRING() PRIMARY KEY,
    execution_timestamp            TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    user_name                       VARCHAR(128) DEFAULT CURRENT_USER(),
    persona_role                    VARCHAR(64) DEFAULT CURRENT_ROLE(),
    nl_question                     TEXT,
    generated_sql                   TEXT,
    metric_contract_id              VARCHAR(32),
    rows_scanned                    NUMBER,
    entitlement_policy_applied      VARCHAR(128),
    semantic_grounding_status       VARCHAR(32) DEFAULT 'GROUNDED_SEMANTIC_SPEC',
    is_refused                      BOOLEAN DEFAULT FALSE,
    refusal_reason                  TEXT
);

